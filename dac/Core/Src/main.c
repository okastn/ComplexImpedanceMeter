/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */
	for (int i = 0; i < DAC_LUT_SIZE; i++){
	float32_t theta = 2*PI * (float32_t)(i)/(float32_t)(DAC_LUT_SIZE);

	/// Converting sine value (-1 to +1) to DAC range from 0 to 4095 for 12-bit)
	sine_LUT[i] = ((arm_cos_f32(theta)*0.95)+1) * (1 << dac_res) /2; //adding headroom by scaling down from 100% to 95% to remove clipping
		}
		freq_out = fsampling/DAC_LUT_SIZE;
		fsampling = 1000000;

		//This represents the fraction of a complete sine cycle per sample
		//phase_inc = ((float64_t)freq_out/ fsampling) * pow(2.0, M);
		//phase_inc = ((uint64_t)freq_out << M) / fsampling;
		//phase_acc = 0;
		//k = log2(NUM_SAMPLES);
  /* USER CODE END 1 */

  /* MPU Configuration--------------------------------------------------------*/
  MPU_Config();

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_DAC_Init();
  MX_TIM6_Init();
  MX_ADC1_Init();
  MX_USART3_UART_Init();
  /* USER CODE BEGIN 2 */
  //HAL_DAC_Start(&hdac, DAC_CHANNEL_1);
  //HAL_TIM_Base_Start_IT(&htim7);
  //uint16_t dac_val = 0;
  HAL_Delay(1000);
  HAL_ADC_Start_DMA(&hadc1, (uint32_t* )adc_buffer, NUM_SAMPLES);
  HAL_DAC_Start_DMA(&hdac, DAC_CHANNEL_1, (uint32_t*)sine_LUT, DAC_LUT_SIZE, DAC_ALIGN_12B_R);
  HAL_TIM_Base_Start(&htim6);

  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
    /* USER CODE END WHILE */
	  if (data_ready_flag)
	      {
	        data_ready_flag = 0;

	        // Determine which half of the buffer to send
	        uint16_t *buffer_ptr;
	        uint16_t samples_to_send;

	        if (buffer_half == 0)
	        {
	          buffer_ptr = adc_buffer; // First half
	          samples_to_send = HALF_SAMPLES;
	        }
	        else
	        {
	          buffer_ptr = &adc_buffer[HALF_SAMPLES]; // Second half
	          samples_to_send = HALF_SAMPLES;
	        }

	        // Transmit the ready half over UART
	        HAL_UART_Transmit(&huart3, (uint8_t*)buffer_ptr, samples_to_send * sizeof(uint16_t), HAL_MAX_DELAY);
	      }

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

